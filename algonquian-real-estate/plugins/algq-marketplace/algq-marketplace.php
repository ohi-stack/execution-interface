/**
 * Safely require a marketplace plugin file if it exists.
 */
function algq_deal_marketplace_require_file(string $relative_path): bool
{
    $file = ALGQ_DEAL_MARKETPLACE_PATH . ltrim($relative_path, '/');

    if (file_exists($file)) {
        require_once $file;
        return true;
    }

    return false;
}

